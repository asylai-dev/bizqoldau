export const STRINGS = { ru, kk }

export function useT() {
  const { lang } = useContext(LangContext)
  const t = (key) => STRINGS[lang][key] ?? STRINGS.ru[key] ?? key
  return { lang, t }
}

// Название региона / сферы / типа на выбранном языке. category: 'Регион' | 'Сфера' | 'Тип'
export function label(lang, category, value) {
  if (lang !== 'kk') return value
  return LABELS_KK[category]?.[value] ?? value
}

function ruPlural(n, forms) {
  const m = n % 10, k = n % 100
  if (m === 1 && k !== 11) return forms[0]
  if (m >= 2 && m <= 4 && (k < 10 || k >= 20)) return forms[1]
  return forms[2]
}

// «3 программы» / «3 бағдарлама»
export function countText(lang, n) {
  return lang === 'kk' ? `${n} бағдарлама` : `${n} ${ruPlural(n, ['программа', 'программы', 'программ'])}`
}

export function formatDate(iso) {
  if (!iso) return ''
  const [y, m, d] = iso.split('-')
  return `${d}.${m}.${y}`
}
